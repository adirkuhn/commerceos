// Markdown renders the catalog page (docs/events.md).
func Markdown(entries []Entry) string {
	var b strings.Builder
	b.WriteString(header)
	fmt.Fprintf(&b, "Domains: %s.\n\n", "`"+strings.Join(events.Domains, "`, `")+"`")
	b.WriteString(envelope)

	b.WriteString("## Catalog\n\n")
	fmt.Fprintf(&b, "%d events. **action** = standard `EntityAction` envelope above; **typed** = its own payload (fields listed).\n", len(entries))
	domain := ""
	for _, e := range entries {
		d := strings.SplitN(e.Subject, ".", 2)[0]
		if d != domain {
			domain = d
			fmt.Fprintf(&b, "\n### %s\n\n| Subject | Kind | Description | Payload |\n|---|---|---|---|\n", d)
		}
		payload := "envelope"
		if e.Kind == "typed" {
			payload = "`" + e.GoType + "`: " + strings.Join(e.Fields, ", ")
		}
		fmt.Fprintf(&b, "| `%s` | %s | %s | %s |\n", e.Subject, e.Kind, escape(e.Description), payload)
	}

	b.WriteString("\n## Legacy subjects\n\nPredate the naming standard; kept so existing consumers keep working. Never add to this list.\n\n")
	for _, e := range entries {
		if events.IsLegacySubject(e.Subject) {
			fmt.Fprintf(&b, "- `%s`\n", e.Subject)
		}
	}
	return b.String()
}

func escape(s string) string { return strings.ReplaceAll(s, "|", `\|`) }

const header = `# Domain events

<!-- Generated by ` + "`go run ./cmd/eventcatalog`" + ` (backend/) from domain/events. Do not edit by hand. -->

Every state-changing action raises a domain event: written to the outbox in
the same transaction as the change, published to NATS JetStream by the relay
(stream subjects ` + "`{domain}.>`" + `). Consumers decide what an event means to them.

## Naming standard

` + "`{domain}.{entity}.{verb}`" + ` -- e.g. ` + "`procurement.purchase_order.created`" + `

- **domain** -- the bounded context, as in ` + "`backend/domain/<domain>`" + ` (one of the domains below).
- **entity** -- the aggregate or record acted on, singular snake_case: ` + "`purchase_order`, `purchase_order_line_item`" + `.
- **verb** -- what happened, past tense snake_case. An event is a fact, never a command:
  ` + "`created`, `updated`, `deleted`, `status_changed`, `item_scanned`" + ` -- not ` + "`create`, `update_status`" + `.
- All lowercase, exactly three dot-separated parts. Enforced by ` + "`domain/events/naming_test.go`" + `.

`

const envelope = `## Standard action event

Raised with one call inside the use case's ` + "`tenant.WithTenant`" + ` transaction:

` + "```go" + `
// 1. register the action once, in domain/events/actions_<domain>.go
SupplierUpdated = defineAction("suppliers.supplier.updated", "A supplier's details were changed.")

// 2. record it in the use case, atomic with the write
return eventrecord.Record(ctx, uc.outbox, events.SupplierUpdated, s.ID,
	eventrecord.NewChanges().Set("name", old.Name, s.Name).Set("lead_time_days", old.LeadTimeDays, s.LeadTimeDays))
` + "```" + `

Payload (` + "`events.EntityAction`" + `):

` + "```json" + `
{
  "event": "suppliers.supplier.updated",
  "event_id": "0b8a…",                       // dedupe key for consumers
  "occurred_at": "2026-10-06T12:00:00Z",
  "tenant_id": "…",
  "actor": { "type": "user", "user_id": "…", "role": "customer_admin" },  // or { "type": "system" }
  "entity_id": "…",
  "changes": { "lead_time_days": { "before": 14, "after": 21 } },          // updates: changed fields only
  "data": { … }                              // action-specific facts, see each event's description
}
` + "```" + `

` + "`changes`" + ` and ` + "`data`" + ` are omitted when empty. Consumers needing the full record read it by ` + "`entity_id`" + `.

`
