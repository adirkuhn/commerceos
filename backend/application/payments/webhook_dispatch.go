// Package payments handles inbound Stripe/Revolut payment webhooks --
// matching a payment-completed event back to the SalesOrder it paid for
// (via the Number/reference stamped into the payment link at generation
// time, see application/whatsapp.GeneratePaymentLinkUseCase) and marking it
// paid. One WebhookDispatchHandler implementation, parameterized per
// provider by a small PaymentEventParser (Open/Closed: a new payment
// provider is a new parser, never a branch added here).
package payments

import (
	"context"
	"fmt"
	"time"

	"gorm.io/gorm"

	omsapp "github.com/adirkuhn/commerceos/application/oms"
	omsDomain "github.com/adirkuhn/commerceos/domain/oms"
	"github.com/adirkuhn/commerceos/domain/webhooks"
	"github.com/adirkuhn/commerceos/internal/tenant"
)

// PaymentEvent is what a provider-specific PaymentEventParser distills a raw
// webhook payload down to. Handled false means the payload is a real,
// correctly-parsed event of a type WebhookDispatchHandler doesn't act on
// (e.g. a Stripe account configured to send every event type, not just
// checkout.session.completed) -- a normal, expected outcome, not an error.
type PaymentEvent struct {
	Handled           bool
	OrderNumber       string
	ExternalPaymentID string
}

// PaymentEventParser turns one provider's raw webhook payload into a
// PaymentEvent. Implementations: StripeEventParser, RevolutEventParser.
type PaymentEventParser interface {
	Parse(rawPayload []byte) (PaymentEvent, error)
}

// SalesOrderUpdater narrows *application/oms.UpdateSalesOrderUseCase to the
// one method this package calls -- a small, package-local interface (ISP)
// rather than importing application/shipping's own identical-shaped
// SalesOrderStatusUpdater, keeping this package's dependency on
// application/oms structural, not a cross-application-package coupling.
type SalesOrderUpdater interface {
	Execute(ctx context.Context, id string, in omsapp.UpdateSalesOrderInput) (*omsDomain.SalesOrder, error)
}

// WebhookDispatchHandler implements application/webhooks.DispatchHandler
// for one payment provider (constructed once per provider with that
// provider's own parser -- see cmd/webhook-processor/main.go).
type WebhookDispatchHandler struct {
	db               *gorm.DB
	salesOrderRepo   omsDomain.SalesOrderRepository
	parser           PaymentEventParser
	updateSalesOrder SalesOrderUpdater
}

func NewWebhookDispatchHandler(db *gorm.DB, salesOrderRepo omsDomain.SalesOrderRepository, parser PaymentEventParser, updateSalesOrder SalesOrderUpdater) *WebhookDispatchHandler {
	return &WebhookDispatchHandler{db: db, salesOrderRepo: salesOrderRepo, parser: parser, updateSalesOrder: updateSalesOrder}
}

// Execute never regresses a SalesOrder that has moved past Pending
// (Completed/Cancelled/Refunded/etc. all stay put -- only TransactionID/
// DatePaid get stamped), and is idempotent against webhook redelivery: a
// SalesOrder that already has DatePaid set is left untouched. An unknown
// order Number (a stray/test webhook, or a payment link generated by a
// tenant this event doesn't belong to) is a no-op, not an error -- same
// convention as HandleOrderStatusWebhookUseCase's unknown MyParcel order
// uuid.
func (h *WebhookDispatchHandler) Execute(ctx context.Context, envelope webhooks.Envelope) error {
	event, err := h.parser.Parse(envelope.RawPayload)
	if err != nil {
		return fmt.Errorf("payments: parse webhook: %w", err)
	}
	if !event.Handled {
		return nil
	}

	ctx = tenant.WithTenantID(ctx, envelope.TenantID)
	var order *omsDomain.SalesOrder
	err = tenant.WithTenant(ctx, h.db, func(ctx context.Context) error {
		o, err := h.salesOrderRepo.FindByNumber(ctx, event.OrderNumber)
		if err != nil {
			return err
		}
		order = o
		return nil
	})
	if err != nil {
		return fmt.Errorf("payments: find order %q: %w", event.OrderNumber, err)
	}
	if order == nil || order.DatePaid != nil {
		return nil
	}

	now := time.Now()
	input := omsapp.UpdateSalesOrderInput{TransactionID: &event.ExternalPaymentID, DatePaid: &now}
	if order.Status == omsDomain.SalesOrderStatusPending {
		processing := omsDomain.SalesOrderStatusProcessing
		input.Status = &processing
	}
	if _, err := h.updateSalesOrder.Execute(ctx, order.ID, input); err != nil {
		return fmt.Errorf("payments: mark order %q paid: %w", event.OrderNumber, err)
	}
	return nil
}
