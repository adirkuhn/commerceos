package pms

import (
	"strings"
)

// Slugify converts a product/category name into a URL-safe slug: lowercase,
// runs of non-alphanumeric characters collapsed to a single "-", leading and
// trailing dashes trimmed.
func Slugify(name string) string {
	var b strings.Builder
	prevDash := false
	for _, r := range strings.ToLower(name) {
		switch {
		case r >= 'a' && r <= 'z' || r >= '0' && r <= '9':
			b.WriteRune(r)
			prevDash = false
		default:
			if !prevDash && b.Len() > 0 {
				b.WriteByte('-')
				prevDash = true
			}
		}
	}
	return strings.TrimSuffix(b.String(), "-")
}
